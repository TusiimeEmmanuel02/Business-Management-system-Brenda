def write_stock_report(rows: List[report_service.StockReportRow], path: Path,
                       *, generated_by: str = "User") -> None:
    doc = _doc(path)
    story: List = []
    story += _header(
        "Stock Report",
        f"Snapshot at {datetime.now().strftime('%d %b %Y %H:%M')}",
        generated_by,
    )
    story.append(_hr_table())
    story.append(Spacer(1, 8))

    table_rows = [
        [r.product_name + (f" ({r.brand})" if r.brand else ""),
         str(r.stock_in), str(r.stock_sold), str(r.remaining),
         format_money(r.buying_price, with_symbol=False),
         format_money(r.selling_price, with_symbol=False),
         format_money(r.stock_value, with_symbol=False),
         format_money(r.estimated_profit, with_symbol=False)]
        for r in rows
    ]
    total_value = sum(r.stock_value for r in rows)
    total_profit = sum(r.estimated_profit for r in rows)
    table_rows.append([
        "TOTAL", "", "", "", "", "",
        format_money(total_value, with_symbol=False),
        format_money(total_profit, with_symbol=False),
    ])
    story.append(_data_table(
        ["Product", "In", "Sold", "Remaining", "Buy", "Sell", "Value", "Est. profit"],
        table_rows,
        col_widths=[45 * mm, 12 * mm, 12 * mm, 18 * mm, 18 * mm, 18 * mm, 25 * mm, 22 * mm],
        right_align_cols=[1, 2, 3, 4, 5, 6, 7],
    ))
    doc.build(story, onFirstPage=_on_page, onLaterPages=_on_page)


def write_labelling_report(rows: List[report_service.LabellingReportRow],
                           period_label: str, path: Path,
                           *, total_revenue: float = 0.0,
                           generated_by: str = "User") -> None:
    s = _styles()
    doc = _doc(path)
    story: List = []
    story += _header("Labelling Jobs Report", _range_subtitle(period_label), generated_by)
    story.append(_hr_table())
    story.append(Spacer(1, 8))

    total_count = sum(r.count for r in rows)
    total_value = sum(r.total_value for r in rows)
    total_outstanding = sum(r.outstanding for r in rows)

    story.append(_kpi_row([
        ("Total Jobs", str(total_count)),
        ("Total Value", format_money(total_value)),
        ("Outstanding", format_money(total_outstanding)),
        ("Revenue (period)", format_money(total_revenue)),
    ]))
    story.append(Spacer(1, 12))

    story.append(Paragraph("Jobs by status", s["h2"]))
    table_rows = [
        [r.status, str(r.count),
         format_money(r.total_value, with_symbol=False),
         format_money(r.outstanding, with_symbol=False)]
        for r in rows
    ]
    table_rows.append([
        "TOTAL", str(total_count),
        format_money(total_value, with_symbol=False),
        format_money(total_outstanding, with_symbol=False),
    ])
    story.append(_data_table(
        ["Status", "Count", "Total (UGX)", "Outstanding (UGX)"],
        table_rows,
        col_widths=[40 * mm, 30 * mm, 50 * mm, 50 * mm],
        right_align_cols=[1, 2, 3],
    ))
    doc.build(story, onFirstPage=_on_page, onLaterPages=_on_page)


def write_profit_loss_report(report: report_service.ProfitLossReport, path: Path,
                             *, generated_by: str = "User") -> None:
    s = _styles()
    doc = _doc(path)
    story: List = []
    story += _header(
        "Profit & Loss Report",
        f"Period: {report.label}  -  "
        f"{format_date(report.start)} to {format_date(report.end)}",
        generated_by,
    )
    story.append(_hr_table())
    story.append(Spacer(1, 8))

    story.append(_kpi_row([
        ("Gross Sales", format_money(report.gross_sales)),
        ("Business Expenses", format_money(report.business_expenses)),
        ("Net Profit", format_money(report.net_profit)),
    ]))
    story.append(Spacer(1, 12))

    story.append(Paragraph("Sales by category", s["h2"]))
    sales_rows = [
        [cat, format_money(amount, with_symbol=False)]
        for cat, amount in report.sales_by_category.items()
    ]
    sales_rows.append(["GROSS SALES",
                       format_money(report.gross_sales, with_symbol=False)])
    story.append(_data_table(
        ["Category", "Amount (UGX)"],
        sales_rows,
        col_widths=[80 * mm, 90 * mm],
        right_align_cols=[1],
    ))

    if report.expenses_by_category:
        story.append(Paragraph("Business expenses", s["h2"]))
        exp_rows = [
            [cat, format_money(amount, with_symbol=False)]
            for cat, amount in report.expenses_by_category.items()
        ]
        exp_rows.append(["TOTAL EXPENSES",
                         format_money(report.business_expenses, with_symbol=False)])
        story.append(_data_table(
            ["Category", "Amount (UGX)"],
            exp_rows,
            col_widths=[80 * mm, 90 * mm],
            right_align_cols=[1],
        ))

    story.append(Paragraph("Net profit", s["h2"]))
    story.append(_data_table(
        ["Item", "Amount (UGX)"],
        [
            ["Gross Sales", format_money(report.gross_sales, with_symbol=False)],
            ["- Business Expenses", format_money(report.business_expenses, with_symbol=False)],
            ["= NET PROFIT", format_money(report.net_profit, with_symbol=False)],
        ],
        col_widths=[100 * mm, 70 * mm],
        right_align_cols=[1],
    ))

    if report.withdrawals_by_reason:
        story.append(Paragraph("Owner withdrawals (separate from profit)", s["h2"]))
        wd_rows = [
            [reason, format_money(amount, with_symbol=False)]
            for reason, amount in report.withdrawals_by_reason.items()
        ]
        wd_rows.append(["TOTAL WITHDRAWALS",
                        format_money(report.owner_withdrawals, with_symbol=False)])
        story.append(_data_table(
            ["Reason", "Amount (UGX)"],
            wd_rows,
            col_widths=[80 * mm, 90 * mm],
            right_align_cols=[1],
        ))

    doc.build(story, onFirstPage=_on_page, onLaterPages=_on_page)
