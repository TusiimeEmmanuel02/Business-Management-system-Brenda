"""
PDF report generation using ReportLab.

All exports share a common header (business name, report title, date range,
generated by, generated on) and footer (page numbers).

Each `write_*` helper takes a populated dataclass / list from
`app.services.report_service` plus an output path and writes the PDF.
"""
from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Iterable, List, Optional, Sequence

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from app.core.utils import format_date, format_money
from app.services import report_service


# ---------------------------------------------------------------------------
# Style helpers
# ---------------------------------------------------------------------------

PRIMARY = colors.HexColor("#2563EB")
DARK = colors.HexColor("#0F172A")
MUTED = colors.HexColor("#64748B")
ROW_ALT = colors.HexColor("#F8FAFC")
BORDER = colors.HexColor("#E2E8F0")
SUCCESS = colors.HexColor("#16A34A")
DANGER = colors.HexColor("#DC2626")


def _styles():
    base = getSampleStyleSheet()
    return {
        "h1": ParagraphStyle(
            "h1", parent=base["Heading1"], fontSize=18, leading=22,
            textColor=DARK, spaceAfter=4,
        ),
        "h2": ParagraphStyle(
            "h2", parent=base["Heading2"], fontSize=13, leading=16,
            textColor=DARK, spaceBefore=12, spaceAfter=6,
        ),
        "meta": ParagraphStyle(
            "meta", parent=base["Normal"], fontSize=9, textColor=MUTED,
            leading=12,
        ),
        "small": ParagraphStyle(
            "small", parent=base["Normal"], fontSize=9, textColor=DARK,
        ),
        "kpi_label": ParagraphStyle(
            "kpi_label", fontSize=8, textColor=MUTED, leading=10,
        ),
        "kpi_value": ParagraphStyle(
            "kpi_value", fontSize=12, textColor=DARK, leading=14, fontName="Helvetica-Bold",
        ),
        "footer": ParagraphStyle(
            "footer", fontSize=8, textColor=MUTED, alignment=1,
        ),
    }


def _header(title: str, subtitle: str, generated_by: str) -> List:
    s = _styles()
    business_name = "Brenda's Printing Hub"
    return [
        Paragraph(f"<b>{business_name}</b>", s["h1"]),
        Paragraph(title, ParagraphStyle(
            "title", parent=s["h2"], fontSize=12, textColor=PRIMARY,
            spaceBefore=0, spaceAfter=2,
        )),
        Paragraph(subtitle, s["meta"]),
        Paragraph(
            f"Generated by: <b>{generated_by}</b> on "
            f"{datetime.now().strftime('%d %b %Y %H:%M')}",
            s["meta"],
        ),
        Spacer(1, 8),
    ]


def _hr_table() -> Table:
    """A 1px tall horizontal-rule rendered as a table."""
    t = Table([[""]], colWidths=[170 * mm], rowHeights=[0.5])
    t.setStyle(TableStyle([
        ("LINEABOVE", (0, 0), (-1, 0), 0.6, BORDER),
    ]))
    return t


def _data_table(headers: Sequence[str], rows: Sequence[Sequence],
                *, col_widths: Optional[Sequence] = None,
                right_align_cols: Sequence[int] = ()) -> Table:
    table_data = [list(headers), *[list(r) for r in rows]]
    table = Table(table_data, colWidths=col_widths, repeatRows=1)
    style = TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F1F5F9")),
        ("TEXTCOLOR", (0, 0), (-1, 0), DARK),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("ALIGN", (0, 0), (-1, -1), "LEFT"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("LINEBELOW", (0, 0), (-1, 0), 0.7, BORDER),
        ("LINEBELOW", (0, -1), (-1, -1), 0.7, BORDER),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, ROW_ALT]),
    ])
    for col in right_align_cols:
        style.add("ALIGN", (col, 0), (col, -1), "RIGHT")
    table.setStyle(style)
    return table


def _kpi_row(items: Sequence[tuple]) -> Table:
    """`items` is a list of (label, value) tuples."""
    s = _styles()
    cells = []
    for label, value in items:
        cells.append([
            Paragraph(label.upper(), s["kpi_label"]),
            Paragraph(value, s["kpi_value"]),
        ])
    cell_tables = []
    for cell in cells:
        t = Table([cell], colWidths=[None])
        t.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("LEFTPADDING", (0, 0), (-1, -1), 8),
            ("RIGHTPADDING", (0, 0), (-1, -1), 8),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("BACKGROUND", (0, 0), (-1, -1), colors.white),
            ("BOX", (0, 0), (-1, -1), 0.6, BORDER),
        ]))
        cell_tables.append(t)
    # Wrap cells side by side
    col_widths = [170 * mm / max(1, len(cell_tables))] * len(cell_tables)
    row = Table([cell_tables], colWidths=col_widths)
    row.setStyle(TableStyle([
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    return row


# ---------------------------------------------------------------------------
# Page footer with page numbers
# ---------------------------------------------------------------------------

def _on_page(canvas, doc):
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(MUTED)
    canvas.drawCentredString(
        A4[0] / 2, 12 * mm,
        f"Brenda's Printing Hub  -  Page {doc.page}",
    )
    canvas.restoreState()


def _doc(path: Path) -> SimpleDocTemplate:
    return SimpleDocTemplate(
        str(path),
        pagesize=A4,
        leftMargin=20 * mm,
        rightMargin=20 * mm,
        topMargin=18 * mm,
        bottomMargin=18 * mm,
        title="Brenda's Printing Hub Report",
        author="Brenda's Printing Hub",
    )


