def _range_subtitle(label: str) -> str:
    return f"Period: {label}"


def write_category_report(rows: List[report_service.CategoryReportRow],
                          period_label: str, path: Path,
                          *, generated_by: str = "User") -> None:
    doc = _doc(path)
    story: List = []
    story += _header("Sales by Category", _range_subtitle(period_label), generated_by)
    story.append(_hr_table())
    story.append(Spacer(1, 8))

    table_rows = [
        [r.category, format_money(r.total, with_symbol=False), f"{r.percentage:.1f}%"]
        for r in rows
    ]
    total = sum(r.total for r in rows)
    table_rows.append(["TOTAL", format_money(total, with_symbol=False), "100.0%"])
    story.append(_data_table(
        ["Category", "Amount (UGX)", "Share"],
        table_rows,
        col_widths=[70 * mm, 60 * mm, 40 * mm],
        right_align_cols=[1, 2],
    ))
    doc.build(story, onFirstPage=_on_page, onLaterPages=_on_page)


