def write_daily_report(report: report_service.DailyReport, path: Path,
                       *, generated_by: str = "User") -> None:
    s = _styles()
    doc = _doc(path)
    story: List = []
    story += _header(
        "Daily Business Report",
        f"For {format_date(report.report_date, '%A, %d %B %Y')}",
        generated_by,
    )
    story.append(_hr_table())
    story.append(Spacer(1, 8))

    story.append(_kpi_row([
        ("Gross Sales", format_money(report.gross_sales)),
        ("Net Profit", format_money(report.net_profit)),
        ("Expected Cash", format_money(report.expected_cash)),
    ]))
    story.append(Spacer(1, 12))

    story.append(Paragraph("Sales by category", s["h2"]))
    story.append(_data_table(
        ["Category", "Amount (UGX)"],
        [
            ["Computer Work", format_money(report.computer_sales, with_symbol=False)],
            ["Fridge / Drinks", format_money(report.fridge_sales, with_symbol=False)],
            ["Labelling", format_money(report.labelling_sales, with_symbol=False)],
            ["GROSS TOTAL", format_money(report.gross_sales, with_symbol=False)],
        ],
        col_widths=[80 * mm, 90 * mm],
        right_align_cols=[1],
    ))

    story.append(Paragraph("Sales by payment method", s["h2"]))
    story.append(_data_table(
        ["Method", "Amount (UGX)"],
        [
            ["Cash", format_money(report.cash_sales, with_symbol=False)],
            ["Mobile Money", format_money(report.mobile_money_sales, with_symbol=False)],
            ["Bank", format_money(report.bank_sales, with_symbol=False)],
        ],
        col_widths=[80 * mm, 90 * mm],
        right_align_cols=[1],
    ))

    story.append(Paragraph("Profitability & cash", s["h2"]))
    story.append(_data_table(
        ["Item", "Amount (UGX)"],
        [
            ["Gross Sales", format_money(report.gross_sales, with_symbol=False)],
            ["- Business Expenses", format_money(report.business_expenses, with_symbol=False)],
            ["= Net Business Profit", format_money(report.net_profit, with_symbol=False)],
            ["Owner Withdrawals (separate)", format_money(report.owner_withdrawals, with_symbol=False)],
            ["Expected Cash on Hand", format_money(report.expected_cash, with_symbol=False)],
        ]
        + (
            [
                ["Actual Cash Counted", format_money(report.actual_cash, with_symbol=False)],
                ["Difference", format_money(report.cash_difference, with_symbol=False)],
            ] if report.has_closing else []
        ),
        col_widths=[100 * mm, 70 * mm],
        right_align_cols=[1],
    ))

    doc.build(story, onFirstPage=_on_page, onLaterPages=_on_page)


